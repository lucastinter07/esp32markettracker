"""Converts the UI's TrueType fonts into Adafruit GFX bitmap fonts (src/ui/fonts/).

Run it again only to change the font list below; the generated files are committed.

  python tools/make_fonts.py <folder with the .ttf files>

The folder needs (SIL Open Font License 1.1, see src/ui/fonts/LICENSE-fonts.txt):
  Inter-var.ttf         https://github.com/google/fonts/raw/main/ofl/inter/Inter%5Bopsz%2Cwght%5D.ttf
  PlexMono-Medium.ttf   https://github.com/google/fonts/raw/main/ofl/ibmplexmono/IBMPlexMono-Medium.ttf
  PlexMono-Regular.ttf  https://github.com/google/fonts/raw/main/ofl/ibmplexmono/IBMPlexMono-Regular.ttf

IBM Plex has the Reserved Font Name "Plex", so the converted (= modified) mono font is
called TrackerMono here. Needs Pillow (pip install pillow).

Glyphs are rendered 1-bit (FreeType's monochrome, hinted mode), which is what the GFX
font format stores. Codes 0x7F-0x83 (not printable ASCII) hold the few non-ASCII characters
the UI uses; ui/fonts.h names them (UI_ELLIPSIS, UI_DOT, UI_NEXT, UI_PREV, UI_DASH).
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

# name, file, pixel size, weight (variable Inter only), first char, last char
FONTS = [
    ("Inter10", "Inter-var.ttf", 10, 400, 0x20, 0x83),
    ("Inter12", "Inter-var.ttf", 12, 400, 0x20, 0x83),
    ("InterSemi10", "Inter-var.ttf", 10, 600, 0x20, 0x83),
    ("InterSemi12", "Inter-var.ttf", 12, 600, 0x20, 0x83),
    ("InterBold15", "Inter-var.ttf", 15, 700, 0x20, 0x83),
    ("InterBold18", "Inter-var.ttf", 18, 700, 0x20, 0x83),
    ("InterBold24", "Inter-var.ttf", 24, 700, 0x20, 0x83),
    ("Mono10", "PlexMono-Medium.ttf", 10, None, 0x20, 0x83),
    ("Mono12", "PlexMono-Medium.ttf", 12, None, 0x20, 0x83),
    ("Mono14", "PlexMono-Medium.ttf", 14, None, 0x20, 0x83),
    ("Mono20", "PlexMono-Medium.ttf", 20, None, 0x20, 0x83),
    ("Mono30", "PlexMono-Medium.ttf", 30, None, 0x20, 0x83),
    ("Mono96", "PlexMono-Regular.ttf", 96, None, 0x30, 0x3A),   # the clock: digits and ':' only
]

# Non-ASCII characters stored in the unused codes after '~' (0x7F is DEL, never printed):
# ellipsis, middle dot, single right / left angle quote, en dash.
EXTRA = {0x7F: "…", 0x80: "·", 0x81: "›", 0x82: "‹", 0x83: "–"}
FALLBACK = {0x7F: ".", 0x80: "-", 0x81: ">", 0x82: "<", 0x83: "-"}   # if a font lacks one


def load(path, size, weight):
    font = ImageFont.truetype(path, size)
    if weight is not None:
        # Inter's axes: optical size (14-32), weight (100-900)
        font.set_variation_by_axes([max(14, min(32, size)), weight])
    return font


def glyph(font, ch):
    """Bitmap bytes, width, height, xAdvance, xOffset, yOffset for one character."""
    advance = int(round(font.getlength(ch)))
    x0, y0, x1, y1 = font.getbbox(ch, mode="1", anchor="ls")
    w, h = x1 - x0, y1 - y0
    if w <= 0 or h <= 0 or ch == " ":
        return b"", 0, 0, advance, 0, 0
    img = Image.new("1", (w, h), 0)
    draw = ImageDraw.Draw(img)
    draw.fontmode = "1"
    draw.text((-x0, -y0), ch, font=font, fill=1, anchor="ls")
    bits = []
    for y in range(h):
        for x in range(w):
            bits.append(1 if img.getpixel((x, y)) else 0)
    out = bytearray()
    for i in range(0, len(bits), 8):
        byte = 0
        for k, b in enumerate(bits[i:i + 8]):
            byte |= b << (7 - k)
        out.append(byte)
    return bytes(out), w, h, advance, x0, y0


def convert(name, path, size, weight, first, last):
    font = load(path, size, weight)
    ascent, descent = font.getmetrics()
    bitmap = bytearray()
    glyphs = []
    missing = glyph(font, "￿")[:3]   # what the font draws for a character it doesn't have
    for code in range(first, last + 1):
        ch = EXTRA.get(code, chr(code))
        data, w, h, adv, xo, yo = glyph(font, ch)
        if code in EXTRA and (data, w, h) == missing:
            print(f"  {name}: no glyph for U+{ord(ch):04X}, using {FALLBACK[code]!r}")
            data, w, h, adv, xo, yo = glyph(font, FALLBACK[code])
        glyphs.append((len(bitmap), w, h, adv, xo, yo, code))
        bitmap += data
    assert len(bitmap) < 65536, name
    lines = [f"// {name}: {os.path.basename(path)} at {size} px"
             + (f", weight {weight}" if weight else "") + ". Generated by tools/make_fonts.py.",
             f"const uint8_t {name}Bitmaps[] PROGMEM = {{"]
    for i in range(0, len(bitmap), 16):
        lines.append("  " + ", ".join(f"0x{b:02X}" for b in bitmap[i:i + 16]) + ",")
    lines.append("};")
    lines.append(f"const GFXglyph {name}Glyphs[] PROGMEM = {{")
    for off, w, h, adv, xo, yo, code in glyphs:
        label = f"U+{ord(EXTRA[code]):04X}" if code in EXTRA else (repr(chr(code)) if code != 0x5C else "backslash")
        lines.append(f"  {{ {off}, {w}, {h}, {adv}, {xo}, {yo} }},   // 0x{code:02X} {label}")
    lines.append("};")
    lines.append(f"const GFXfont {name} PROGMEM = {{ (uint8_t *){name}Bitmaps, (GFXglyph *){name}Glyphs, "
                 f"0x{first:02X}, 0x{last:02X}, {ascent + descent} }};")
    lines.append(f"// {len(bitmap)} bitmap bytes, {len(glyphs)} glyphs")
    return "\n".join(lines) + "\n", len(bitmap) + 7 * len(glyphs)


def main():
    src = sys.argv[1]
    here = os.path.dirname(os.path.abspath(__file__))
    out_dir = os.path.join(here, "..", "src", "ui", "fonts")
    os.makedirs(out_dir, exist_ok=True)
    total = 0
    names = []
    for name, file, size, weight, first, last in FONTS:
        text, nbytes = convert(name, os.path.join(src, file), size, weight, first, last)
        with open(os.path.join(out_dir, f"{name}.h"), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        names.append(name)
        total += nbytes
        print(f"{name}: {nbytes} bytes")
    # fonts.cpp gives every font external linkage (declared extern in ui/fonts.h first).
    with open(os.path.join(here, "..", "src", "ui", "fonts.cpp"), "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/make_fonts.py: the UI fonts' data, declared in ui/fonts.h.\n")
        f.write('#include "ui/fonts.h"\n')
        for n in names:
            f.write(f'#include "ui/fonts/{n}.h"\n')
    print(f"total ~{total} bytes of flash")


if __name__ == "__main__":
    main()
